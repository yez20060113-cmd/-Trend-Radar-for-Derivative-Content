# 与二创几乎不交叉：单命中即判噪声（但仍要求「素材名命中」或「≥2 条样本命中」）
HARD_NOISE_GROUPS = {"体育", "电竞"}


def _ascii_word(word: str) -> bool:
    return bool(word) and word.isascii() and any(ch.isalpha() for ch in word)


def hit(low: str, word: str) -> bool:
    """单个词是否命中。英文按词边界，中文按子串。调用方需先转小写。"""
    if not word:
        return False
    if _ascii_word(word):
        return bool(re.search(rf"(?<![a-z0-9]){re.escape(word)}(?![a-z0-9])", low))
    return word in low


def hits(low: str, words: list[str]) -> list[str]:
    """返回在文本中命中的词（要求调用方先转小写）。"""
    return [w for w in words if hit(low, w)]
